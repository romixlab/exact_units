//! Levels in dB (STD-67): the gains `from_db_const` works out at compile time against an 80-digit reference and
//! libm's `exp10`, and the run-time `to_db` / `from_db` in `f64` and `f32`.
#![cfg(feature = "electrical")]

use exact_units::decibel::Decibels;
use exact_units::prefix::{Micro, Milli, Nano, One, Rational};
use exact_units::units::{Ampere, Per, Volt, Watt};
use exact_units::{Fixed, db};

type VoltGain<P, T> = Fixed<Per<Volt, Volt>, P, T>;
type PowerGain<P, T> = Fixed<Per<Watt, Watt>, P, T>;

/// Levels from −120 to +60 dB in odd steps of up to three decimals, so few land on a round number.
fn levels() -> impl Iterator<Item = Decibels> {
    (-120_000i64..=60_000)
        .step_by(373)
        .map(|n| Decibels::new(n, 3))
}

/// Levels whose exponent is exact in `f64`: steps of 0.3125 dB are 1/64 decade of a root-power gain (and 1/32 of a
/// power gain), so libm's `exp10` gets the exact input and its error is its own.
fn dyadic_levels() -> impl Iterator<Item = (Decibels, f64)> {
    (-384i64..=192).map(|m| (Decibels::new(m * 3125, 4), m as f64 / 64.0))
}

/// How far an `f64` reference may be from the exact gain, relative: libm's own ulp and the rounding of its input
/// `y = dB / 20`, which `10^y` turns into `ln 10 · |y|` times as much.
fn tolerance(y: f64) -> f64 {
    (2.0 + 2.31 * y.abs()) * f64::EPSILON
}

fn ulps(a: f64, b: f64) -> u64 {
    a.to_bits().abs_diff(b.to_bits())
}

