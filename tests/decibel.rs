#[cfg(any(feature = "std", feature = "libm"))]
mod run_time {
    use super::*;

    #[test]
    fn f32_and_f64_agree() {
        for db in levels() {
            let x = db.to_f64();
            let g = VoltGain::<One, f64>::from_db(x).unwrap();
            let g32 = VoltGain::<One, f32>::from_db_f32(x as f32).unwrap();
            assert!((g32.get() as f64 / g.get() - 1.0).abs() < 1e-5, "{x} dB");
            let back = g.to_db();
            assert!((back - x).abs() < 1e-9, "{x} dB: {back}");
            let back32 = g32.to_db_f32();
            assert!(
                (back32 as f64 - x).abs() < 1e-3 + x.abs() * 1e-6,
                "{x} dB: {back32}"
            );
        }
    }

    #[test]
    fn integer_storage_in_f32() {
        let g = VoltGain::<Milli, u16>::new(100);
        assert_eq!(g.to_db_f32(), -20.0);
        assert_eq!(
            PowerGain::<Milli, u32>::from_db_f32(20.0),
            Some(Fixed::new(100_000))
        );
        // not a whole number of the storage
        assert_eq!(VoltGain::<One, u16>::from_db_f32(3.0), None);
        // the compile-time and the run-time gain agree
        let c: VoltGain<Micro, u32> = db!(-6);
        let r = VoltGain::<Micro, f32>::from_db_f32(-6.0).unwrap();
        assert!((c.get() as f32 - r.get()).abs() <= 1.0);
    }
}
